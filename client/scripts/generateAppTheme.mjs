import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const files = directory => fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(path.join(directory, entry.name)) : [path.join(directory, entry.name)]);
const tokens = new Set();
for (const file of files(root).filter(file => /\.(jsx|css)$/.test(file) && !file.endsWith('AppThemeUtilities.css'))) {
    const source = fs.readFileSync(file, 'utf8');
    for (const match of source.matchAll(/(?<![\w-])((?:(?:hover|focus|focus-visible|disabled|sm|md|lg|xl|2xl|dark):)*)(bg|text|border|divide|from|via|to)-(white|black|(?:slate|gray|zinc|neutral|stone|blue|indigo|sky|cyan|teal|emerald|green|lime|amber|yellow|orange|red|rose|pink|purple|violet|fuchsia)-\d{2,3}|\[#[\da-fA-F]{3,8}\])(?:\/(\d{1,3}))?(?![\w-])/g)) tokens.add(match[0]);
}
const guard = ':not([data-theme-paper], [data-theme-paper] *, [data-theme-fixed], [data-theme-fixed] *)';
const breaks = { sm:640, md:768, lg:1024, xl:1280, '2xl':1536 };
const esc = value => value.replace(/[^a-zA-Z0-9_-]/g, value => `\\${value}`);
const output = ['/* Generated by scripts/generateAppTheme.mjs. Compatibility for existing utility-based UI. */', '@media screen {'];
const lightSurfaces = [];
for (const token of [...tokens].sort()) {
    const parts = token.split(':');
    const base = parts.pop(), variants = parts;
    if (variants.includes('dark')) continue; // Explicit dark variants remain authored by the component.
    const match = base.match(/^(bg|text|border|divide|from|via|to)-(.+?)(?:\/(\d+))?$/);
    if (!match) continue;
    const [, role, color, opacity] = match;
    const background = ['bg', 'from', 'via', 'to'].includes(role);
    let neutral = /^(white|black|(?:slate|gray|zinc|neutral|stone)-)/.test(color);
    const shade = Number(color.match(/-(\d+)$/)?.[1] || (color === 'white' ? 0 : 950));
    if (color.startsWith('[#')) {
        const raw = color.slice(2, -1);
        const hex = raw.length === 3 ? [...raw].map(c => c + c).join('') : raw.slice(0, 6);
        const channels = [0, 2, 4].map(index => parseInt(hex.slice(index, index + 2), 16) / 255);
        neutral = Math.max(...channels) - Math.min(...channels) < .22;
        if (!neutral) continue; // Saturated custom colors represent branding, uniforms, or courts.
    }
    let variable;
    if (neutral) {
        if (color === 'black' && role === 'bg' && opacity) continue; // Modal scrims stay translucent black.
        if (background) variable = shade >= 600 || shade === 0 ? '--app-surface' : shade <= 200 ? '--app-surface-alt' : '--app-control';
        if (role === 'text') {
            if (color === 'white') {
                if (!variants.some(value => ['hover', 'focus', 'focus-visible'].includes(value))) continue;
                variable = '--app-text'; // Preserve light interactive foregrounds over solid actions.
            } else variable = shade >= 700 || shade <= 300 ? '--app-text' : shade === 600 ? '--app-muted' : '--app-soft';
        }
        if (role === 'border' || role === 'divide') {
            if (color === 'white' || color === 'black') continue; // Court lines and report borders.
            variable = '--app-border';
        }
    } else {
        const family = color.split('-')[0];
        const kind = /blue|indigo|sky|cyan/.test(family) ? 'info' : /emerald|green|teal|lime/.test(family) ? 'success' : /amber|yellow|orange/.test(family) ? 'warning' : /purple|violet|fuchsia/.test(family) ? 'purple' : 'danger';
        if (background && shade <= 200) variable = `--app-${kind}-bg`;
        if (role === 'text' && shade >= 500) variable = `--app-${kind}-text`;
        if ((role === 'border' || role === 'divide') && shade <= 300) variable = `--app-${kind}-text`;
    }
    if (!variable) continue;
    const property = ['from', 'via', 'to'].includes(role) ? `--tw-gradient-${role}` : role === 'bg' ? 'background-color' : role === 'text' ? 'color' : 'border-color';
    const value = opacity ? `color-mix(in srgb, var(${variable}) ${Math.min(100, Number(opacity))}%, transparent)` : `var(${variable})`;
    const pseudo = variants.filter(v => !breaks[v]).map(v => `:${v}`).join('');
    const target = `:where(.${esc(token)})${pseudo}${guard}`;
    if (neutral && role === 'bg' && shade >= 600 && !opacity && !variants.length) {
        const surface = `${target}:not(button, a, input)`;
        lightSurfaces.push(`.${esc(token)}:not(button, a, input)`);
        output.push(`html[data-app-theme="light"] ${surface} { background-color:var(--app-surface); color:var(--app-text); }`);
    }
    let rule = `html[data-app-theme="dark"] ${target}${role === 'divide' ? ' > :not(:last-child)' : ''} { ${property}:${value}; }`;
    for (const variant of variants.filter(v => breaks[v]).reverse()) rule = `@media (min-width:${breaks[variant]}px) { ${rule} }`;
    output.push(rule);
}
if (lightSurfaces.length) {
    const coloredControls = ':is(button,a)[class*="bg-"]';
    output.push(`html[data-app-theme="light"] :is(${lightSurfaces.join(',')}) :where(.text-white,.text-slate-100,.text-slate-200,.text-slate-300,.text-gray-100,.text-gray-200,.text-gray-300)${guard}:not(${coloredControls}, ${coloredControls} *) { color:var(--app-text); }`);
}
output.push('}', '');
const filename = path.join(root, 'styles/AppThemeUtilities.css');
const source = output.join('\n');
if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== source) fs.writeFileSync(filename, source);
