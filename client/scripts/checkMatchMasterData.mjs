import assert from 'node:assert/strict';
import http from 'node:http';
import {createRequire} from 'node:module';
import {createServer} from 'vite';
import {chromium} from 'playwright-core';
const require=createRequire(import.meta.url);
process.env.DB_PROVIDER='postgres';
const {setup}=require('../../backend/tests/helpers/postgresHarness');
let harness,server,vite,browser,page;
try{
    harness=await setup();const db=harness.db;
    // Native advisory-lock clients cannot connect to PGlite. Keep scope checks on
    // this isolated database; native serialization is covered by the native suites.
    Object.assign(process.env,{DB_HOST:'127.0.0.1',DB_PORT:'1',DB_NAME:'isolated_test',DB_USER:'test',DB_PASSWORD:'test',DB_SSL:'false'});
    delete process.env.DATABASE_URL;
    require('../../backend/middleware/recordingLock').holdRecordingAccess=async(req,res,kind,id,permission,options)=>require('../../backend/utils/accessScope').assertMatch(db,req.user,kind,id,permission,options);
    await db.query("INSERT INTO users(id,username,password_hash,role,status) VALUES(1,'Scorer browser test','x','scorer','active')");
    await db.query("INSERT INTO age_groups(id,name) VALUES(1,'Open')");
    await db.query("INSERT INTO competitions(id,title,sport,gender,age_group_id,max_sets,start_date,max_players) VALUES(1,'Master data browser test','volleyball','Male',1,3,'2026-11-17',12)");
    await db.query('INSERT INTO user_competition_access(user_id,competition_id) VALUES(1,1)');
    await db.query("INSERT INTO teams(id,name,code) VALUES(10,'Home Team','HOME'),(20,'Away Team','AWAY')");
    await db.query("INSERT INTO team_entries(competition_id,team_id,gender,age_group_id,status) VALUES(1,10,'Male',1,'approved'),(1,20,'Male',1,'approved')");
    await db.query("INSERT INTO matches(id,competition_id,home_team_id,away_team_id,status,max_sets) VALUES(1,1,10,20,'scheduled',3)");
    process.env.FRONTEND_URL='http://localhost:5187';process.env.CORS_ORIGINS='';
    server=http.createServer(require('../../backend/server').app);await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
    const origin=`http://127.0.0.1:${server.address().port}`;
    vite=await createServer({server:{host:'localhost',port:5187,strictPort:true},define:{'import.meta.env.VITE_API_URL':JSON.stringify(origin)}});await vite.listen();
    const user=(await db.query('SELECT id,username,role,status,authorization_version FROM users WHERE id=1')).rows[0];
    const token=require('../../backend/node_modules/jsonwebtoken').sign(user,process.env.JWT_SECRET,{expiresIn:'10m'});
    const matchId=(await db.query('SELECT public_id FROM matches WHERE id=1')).rows[0].public_id;
    browser=await chromium.launch({channel:'msedge',headless:true});page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.addInitScript(({token,user})=>{sessionStorage.setItem('token',token);sessionStorage.setItem('user',JSON.stringify(user));localStorage.setItem('language','ENG');},{token,user});
    await page.goto(`http://localhost:5187/scripts/fixtures/match-master-data.html?matchId=${matchId}`);
    await page.getByRole('tab',{name:'Teams',exact:true}).click();
    const home=page.locator('.smm-teams > section').first();
    await home.getByRole('button',{name:'Create athlete and add to match',exact:true}).click();
    await page.getByLabel('New master home players first_name',{exact:true}).fill('New Athlete');
    await page.getByLabel('New master home players last_name',{exact:true}).fill('Browser');
    await page.getByLabel('New master home number',{exact:true}).fill('7');
    await home.getByRole('button',{name:'Add to pending changes',exact:true}).click();
    assert.equal(Number((await db.query('SELECT count(*) AS count FROM players')).rows[0].count),0,'draft does not create master records');
    await page.getByRole('button',{name:'Save master data and add to match',exact:true}).click();
    await page.getByText('Master data created and added to this match.',{exact:true}).waitFor();
    assert.equal(Number((await db.query('SELECT count(*) AS count FROM players WHERE team_id=10')).rows[0].count),1);
    await page.getByRole('tab',{name:/^Team [Ss]taff$/}).click();
    await home.getByRole('button',{name:'Create team staff and add to match',exact:true}).click();
    await page.getByLabel('New master home staff first_name',{exact:true}).fill('New Coach');
    await page.getByLabel('New master home staff last_name',{exact:true}).fill('Browser');
    await home.getByRole('button',{name:'Add to pending changes',exact:true}).click();
    await page.getByRole('button',{name:'Save master data and add to match',exact:true}).click();
    await page.getByText('Master data created and added to this match.',{exact:true}).waitFor();
    assert.equal(Number((await db.query('SELECT count(*) AS count FROM team_staff WHERE team_id=10')).rows[0].count),1);
    await home.getByRole('textbox',{name:'Home Team First name 1',exact:true}).fill('Updated Coach');
    const postSaveReads=[];
    const trackReads=request=>{if(request.method()==='GET'&&request.url().startsWith(origin+'/api/'))postSaveReads.push(request.url());};
    page.on('request',trackReads);
    await page.getByRole('button',{name:'Save and close',exact:true}).click();
    await page.getByRole('button',{name:'Open settings',exact:true}).waitFor();
    page.off('request',trackReads);
    assert.deepEqual(postSaveReads,[],'save and close does not reload the discarded modal snapshot');
    await page.getByRole('button',{name:'Open settings',exact:true}).click();
    await page.getByRole('tab',{name:/^Team [Ss]taff$/}).click();
    await home.getByRole('button',{name:'Create team staff and add to match',exact:true}).waitFor();
    assert.equal(await home.getByRole('textbox',{name:'Home Team First name 1',exact:true}).inputValue(),'Updated Coach');
    await home.getByRole('button',{name:'Create team staff and add to match',exact:true}).click();
    await page.getByRole('dialog').screenshot({path:'match-master-data-browser.png'});
    await page.getByLabel('New master home staff first_name',{exact:true}).fill('New Coach');
    await page.getByLabel('New master home staff last_name',{exact:true}).fill('Browser');
    await home.getByRole('button',{name:'Add to pending changes',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'This name already exists'}).waitFor();
    await home.getByRole('button',{name:'Cancel',exact:true}).click();
    await page.getByRole('tab',{name:'Teams',exact:true}).click();
    const away=page.locator('.smm-teams > section').last();
    await away.getByRole('button',{name:'Create athlete and add to match',exact:true}).click();
    await page.getByLabel('New master away players first_name',{exact:true}).fill('Cancelled');
    await page.getByLabel('New master away number',{exact:true}).fill('8');
    await away.getByRole('button',{name:'Add to pending changes',exact:true}).click();
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'Cancel / Close',exact:true}).click();
    assert.equal(Number((await db.query('SELECT count(*) AS count FROM players WHERE team_id=20')).rows[0].count),0);
    assert.deepEqual(errors,[]);
    console.log('Passed: actual Scorer settings create athlete and team staff in master + entry + match, reopen, duplicate detection and cancel without writes.');
}catch(error){if(page)console.error((await page.locator('body').innerText()).slice(-4000));throw error;}
finally{await browser?.close();await vite?.close();if(server){server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}await harness?.close();}
