import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
const sources = ['backend/config/visCodes.js', 'backend/utils/visWorkflow.js', 'backend/utils/customVis.js', 'backend/utils/importCustomVis.js'];
const chunks = sources.map(path => fs.readFileSync(`${root}${path}`, 'utf8')
    .replace(/^const .* = require\([^\n]+\);\r?\n/gm, '')
    .replace(/module\.exports\s*=\s*\{[^}]+\};?/gs, ''));
const output = '/* eslint-disable */\n// Generated by scripts/generateVisEngine.mjs. Do not edit; parity-tested against backend.\n' + chunks.join('\n') + '\nexport { createPayload, view, commandPayload, importCustomVis };\n';
const target = `${root}client/src/offline/visEngine.js`;
fs.mkdirSync(`${root}client/src/offline`, {recursive:true});
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw Error('Offline VIS engine is stale: run node scripts/generateVisEngine.mjs');
} else fs.writeFileSync(target, output);
