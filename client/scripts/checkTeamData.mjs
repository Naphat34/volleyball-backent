import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {build} from 'vite';
const require=createRequire(import.meta.url),{chromium}=require('playwright-core');
const directory=fileURLToPath(new URL('../../tmp/team-data-build/',import.meta.url));
await build({logLevel:'error',publicDir:false,build:{outDir:directory,emptyOutDir:false,rollupOptions:{input:fileURLToPath(new URL('./fixtures/team-data.html',import.meta.url))}}});
const browser=await chromium.launch({headless:true,channel:'msedge'}),page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
try{
    await page.route('**/*',async route=>{const url=new URL(route.request().url());if(url.hostname!=='team-data.test')return route.abort();try{await route.fulfill({body:await readFile(directory+url.pathname),contentType:url.pathname.endsWith('.js')?'application/javascript':url.pathname.endsWith('.css')?'text/css':'text/html'});}catch{await route.fulfill({status:404,body:''});}});
    await page.goto('http://team-data.test/scripts/fixtures/team-data.html');
    await page.getByRole('heading',{name:'Team data center',exact:true}).waitFor();
    await page.getByRole('button',{name:'Use Thai',exact:true}).click();
    await page.getByRole('heading',{name:'ศูนย์ข้อมูลทีม',exact:true}).waitFor();
    await page.getByRole('button',{name:'Use English',exact:true}).click();
    await page.getByRole('button',{name:'Competition rosters',exact:true}).click();
    await page.getByRole('button',{name:'Select and confirm',exact:true}).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('checkbox',{name:'Select Player 7 Family',exact:true}).check();
    const buttons=await page.getByRole('dialog').getByRole('button').allTextContents();
    const confirm=buttons.find(text=>/confirm/i.test(text));assert.ok(confirm,buttons.join('|'));
    await page.getByRole('dialog').getByRole('button',{name:confirm,exact:true}).click();
    await page.waitForFunction(()=>window.savedSelection);
    const selection=await page.evaluate(()=>window.savedSelection);assert.equal(selection.players.length,7);assert.equal(selection.players[6].master_revision,0);assert.equal(selection.confirm,true);
    await page.screenshot({path:directory+'team-data.png',fullPage:true});
    await page.getByRole('button',{name:'Athletes',exact:true}).click();
    const ExcelJS=require('exceljs'),workbook=new ExcelJS.Workbook(),sheet=workbook.addWorksheet('Players');
    sheet.addRow(['number','first_name','last_name','position','birth_date']);
    sheet.addRow([8,'New','Athlete','OH','2010-01-01']);sheet.addRow([9,'','Incomplete','OH','2010-01-01']);
    await page.locator('input[type=file]').setInputFiles({name:'players.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(await workbook.xlsx.writeBuffer())});
    await page.getByRole('dialog',{name:'Review imported players',exact:true}).waitFor();
    assert.ok(await page.getByRole('checkbox',{name:'Select row 2',exact:true}).isChecked());
    assert.ok(await page.getByRole('checkbox',{name:'Select row 3',exact:true}).isDisabled());
    await page.getByRole('button',{name:'Import selected rows',exact:true}).click();
    await page.waitForFunction(()=>window.savedPlayer);
    assert.equal((await page.evaluate(()=>window.savedPlayer)).number,'8');
    await page.getByRole('dialog').getByRole('button',{name:'Close',exact:true}).last().click();
    await page.goto('http://team-data.test/scripts/fixtures/team-data.html?admin');
    await page.getByRole('heading',{name:'Team roster change requests',exact:true}).waitFor();
    await page.getByText('Compare current roster and proposal',{exact:true}).click();
    await page.getByRole('textbox').fill('Verified athlete change');
    await page.getByRole('button',{name:'Approve roster',exact:true}).click();
    await page.waitForFunction(()=>window.savedDecision);assert.equal((await page.evaluate(()=>window.savedDecision)).decision,'approved');
    assert.deepEqual(errors,[]);console.log('Team center Thai/English, manual selection, selective Excel import and Super Admin decision browser checks passed.');
}finally{await browser.close();}
