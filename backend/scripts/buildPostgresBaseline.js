// Generate a reviewed baseline from exportMysqlSchema metadata, never application rows.
const fs = require('node:fs');
const path = require('node:path');
const quote = name => '"' + name.replaceAll('"', '""') + '"';
const literal = value => "'" + value.replaceAll("'", "''") + "'";
function expression(value) {
    return value.replace(/_utf8mb4/g, '').replace(/\\'/g, "'").replace(/`([^`]+)`/g, (_, name) => quote(name));
}
function generate(source) {
    if (source.TRIGGERS.length) throw new Error('Source triggers require explicit translation');
    if (source.TABLES.some(table => table.TABLE_TYPE !== 'BASE TABLE')) throw new Error('Source views require explicit translation');
    const lines = ['-- Baseline generated from source MySQL metadata; no application data.',
        '-- Dedicated schema keeps application tables outside Supabase public Data API.',
        'CREATE SCHEMA volley;', 'REVOKE ALL ON SCHEMA volley FROM PUBLIC;',
        'SET search_path TO volley, public;',
        "CREATE FUNCTION valid_json(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT AS $$ BEGIN PERFORM value::jsonb; RETURN true; EXCEPTION WHEN invalid_text_representation THEN RETURN false; END $$;",
        "CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END $$;",
    ];
    const tables = source.TABLES.filter(table => !['schema_migrations', 'seed_migrations'].includes(table.TABLE_NAME));
    for (const { TABLE_NAME: table } of tables) {
        const columns = source.COLUMNS.filter(col => col.TABLE_NAME === table).sort((a,b) => a.ORDINAL_POSITION-b.ORDINAL_POSITION);
        const definitions = columns.map(col => {
            let type;
            switch (col.DATA_TYPE) {
                case 'int': case 'mediumint': type = 'integer'; break;
                case 'tinyint': case 'smallint': type = 'smallint'; break;
                case 'bigint': type = 'bigint'; break;
                case 'varchar': case 'char': type = `varchar(${col.CHARACTER_MAXIMUM_LENGTH})`; break;
                case 'text': case 'mediumtext': case 'longtext': type = 'text'; break;
                case 'enum': type = 'text'; break;
                case 'decimal': type = `numeric(${col.NUMERIC_PRECISION},${col.NUMERIC_SCALE})`; break;
                case 'double': type = 'double precision'; break;
                case 'float': type = 'real'; break;
                case 'json': type = 'jsonb'; break;
                case 'timestamp': type = 'timestamptz'; break;
                case 'datetime': type = 'timestamp'; break;
                case 'date': case 'time': type = col.DATA_TYPE; break;
                default: throw new Error(`Unsupported type ${table}.${col.COLUMN_NAME}: ${col.DATA_TYPE}`);
            }
            let definition = `${quote(col.COLUMN_NAME)} ${type}`;
            if (col.GENERATION_EXPRESSION) definition += ` GENERATED ALWAYS AS (${expression(col.GENERATION_EXPRESSION)}) STORED`;
            else if (col.EXTRA.includes('auto_increment')) definition += ' GENERATED BY DEFAULT AS IDENTITY';
            else if (col.COLUMN_DEFAULT !== null) {
                const value = String(col.COLUMN_DEFAULT);
                definition += ` DEFAULT ${/^CURRENT_TIMESTAMP(?:\(\))?$/i.test(value) ? 'CURRENT_TIMESTAMP' : literal(value)}`;
            }
            if (col.IS_NULLABLE === 'NO') definition += ' NOT NULL';
            if (col.DATA_TYPE === 'enum') definition += ` CHECK (${quote(col.COLUMN_NAME)} IN (${col.COLUMN_TYPE.slice(5,-1)}))`;
            if (/unsigned/i.test(col.COLUMN_TYPE)) definition += ` CHECK (${quote(col.COLUMN_NAME)} >= 0)`;
            return definition;
        });
        const constraints = source.TABLE_CONSTRAINTS.filter(c => c.TABLE_NAME === table && ['PRIMARY KEY','CHECK'].includes(c.CONSTRAINT_TYPE));
        for (const constraint of constraints) {
            if (constraint.CONSTRAINT_TYPE === 'PRIMARY KEY') {
                const keys = source.KEY_COLUMN_USAGE.filter(k => k.TABLE_NAME === table && k.CONSTRAINT_NAME === constraint.CONSTRAINT_NAME).sort((a,b)=>a.ORDINAL_POSITION-b.ORDINAL_POSITION);
                definitions.push(`PRIMARY KEY (${keys.map(k => quote(k.COLUMN_NAME)).join(', ')})`);
            } else {
                const check = source.CHECK_CONSTRAINTS.find(c => c.CONSTRAINT_NAME === constraint.CONSTRAINT_NAME);
                if (!check) throw new Error(`Missing check ${constraint.CONSTRAINT_NAME}`);
                definitions.push(`CONSTRAINT ${quote(constraint.CONSTRAINT_NAME)} CHECK (${expression(check.CHECK_CLAUSE).replace(/json_valid\(/gi, 'valid_json(')})`);
            }
        }
        lines.push(`CREATE TABLE ${quote(table)} (\n    ${definitions.join(',\n    ')}\n);`);
        if (columns.some(col => /on update CURRENT_TIMESTAMP/i.test(col.EXTRA))) lines.push(`CREATE TRIGGER touch_updated_at BEFORE UPDATE ON ${quote(table)} FOR EACH ROW EXECUTE FUNCTION touch_updated_at();`);
    }
    for (const { TABLE_NAME: table } of tables) {
        const indexes = new Map();
        for (const index of source.STATISTICS.filter(i=>i.TABLE_NAME===table && i.INDEX_NAME!=='PRIMARY')) {
            if (index.SUB_PART || index.EXPRESSION || index.INDEX_TYPE !== 'BTREE') throw new Error(`Unsupported index ${table}.${index.INDEX_NAME}`);
            const group = indexes.get(index.INDEX_NAME) || []; group.push(index); indexes.set(index.INDEX_NAME,group);
        }
        for (const [name, members] of indexes) {
            const cols = members.sort((a,b)=>a.SEQ_IN_INDEX-b.SEQ_IN_INDEX).map(i=>quote(i.COLUMN_NAME)).join(', ');
            const indexName = `${table}_${name}`;
            if (indexName.length > 63) throw new Error(`Index name too long: ${indexName}`);
            lines.push(`CREATE ${members[0].NON_UNIQUE ? '' : 'UNIQUE '}INDEX ${quote(indexName)} ON ${quote(table)} (${cols});`);
        }
    }
    for (const fk of source.REFERENTIAL_CONSTRAINTS.filter(f=>tables.some(t=>t.TABLE_NAME===f.TABLE_NAME))) {
        const keys=source.KEY_COLUMN_USAGE.filter(k=>k.TABLE_NAME===fk.TABLE_NAME && k.CONSTRAINT_NAME===fk.CONSTRAINT_NAME).sort((a,b)=>a.ORDINAL_POSITION-b.ORDINAL_POSITION);
        lines.push(`ALTER TABLE ${quote(fk.TABLE_NAME)} ADD CONSTRAINT ${quote(fk.CONSTRAINT_NAME)} FOREIGN KEY (${keys.map(k=>quote(k.COLUMN_NAME)).join(', ')}) REFERENCES ${quote(fk.REFERENCED_TABLE_NAME)} (${keys.map(k=>quote(k.REFERENCED_COLUMN_NAME)).join(', ')}) ON UPDATE ${fk.UPDATE_RULE} ON DELETE ${fk.DELETE_RULE};`);
    }
    // Keep users' case-insensitive login uniqueness, including concurrent registration.
    lines.push('CREATE UNIQUE INDEX users_username_casefold ON users (lower(username));');
    lines.push('REVOKE ALL ON ALL TABLES IN SCHEMA volley FROM PUBLIC;', 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA volley FROM PUBLIC;');
    return lines.join('\n\n')+'\n';
}
if (require.main === module) {
    const snapshot = JSON.parse(fs.readFileSync(process.argv[2] ? path.resolve(process.argv[2]) : path.join(__dirname,'../../tmp/mysql-schema.json'),'utf8'));
    const target=path.join(__dirname,'..','migrations','postgres','001_baseline.sql');
    fs.mkdirSync(path.dirname(target),{recursive:true});
    fs.writeFileSync(target,generate(snapshot));
    console.log('Generated PostgreSQL baseline');
}
module.exports={generate};
