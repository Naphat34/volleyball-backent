CREATE TABLE match_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id integer REFERENCES matches(id) ON DELETE RESTRICT,
    custom_match_id varchar(48) REFERENCES custom_vis_matches(id) ON DELETE RESTRICT,
    domain varchar(10) NOT NULL CHECK(domain IN ('score','vims')),
    competition_id integer NOT NULL REFERENCES competitions(id) ON DELETE RESTRICT,
    revision integer NOT NULL CHECK(revision>0), fingerprint varchar(64) NOT NULL,
    status varchar(20) NOT NULL CHECK(status IN ('submitted','confirmed','returned','reopened')),
    submitted_by integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    submitted_at timestamptz NOT NULL DEFAULT now(),
    decided_by integer REFERENCES users(id) ON DELETE RESTRICT, decided_at timestamptz, reason text,
    CHECK((match_id IS NOT NULL AND custom_match_id IS NULL) OR (match_id IS NULL AND custom_match_id IS NOT NULL AND domain='vims'))
);
CREATE UNIQUE INDEX match_reviews_official_revision ON match_reviews(match_id,domain,revision) WHERE match_id IS NOT NULL;
CREATE UNIQUE INDEX match_reviews_custom_revision ON match_reviews(custom_match_id,domain,revision) WHERE custom_match_id IS NOT NULL;
CREATE INDEX match_reviews_queue ON match_reviews(competition_id,domain,status);
CREATE FUNCTION bump_account_authorization() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
    IF NEW.role IS DISTINCT FROM OLD.role OR NEW.status IS DISTINCT FROM OLD.status THEN
        NEW.authorization_version := OLD.authorization_version+1;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER users_authorization_version BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION bump_account_authorization();
CREATE FUNCTION bump_competition_authorization() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
    UPDATE users SET authorization_version=authorization_version+1 WHERE id=COALESCE(NEW.user_id,OLD.user_id);
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER competition_authorization_version AFTER INSERT OR UPDATE OR DELETE ON user_competition_access
    FOR EACH ROW EXECUTE FUNCTION bump_competition_authorization();

