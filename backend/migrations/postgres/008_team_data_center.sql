-- Existing rosters remain confirmed. New entries require explicit team selection.
ALTER TABLE volley.team_entries ADD COLUMN roster_mode text NOT NULL DEFAULT 'manual' CHECK(roster_mode IN ('manual','auto'));
ALTER TABLE volley.team_entries ADD COLUMN roster_revision integer NOT NULL DEFAULT 0;
ALTER TABLE volley.team_entries ADD COLUMN roster_confirmed_at timestamptz;
ALTER TABLE volley.team_entries ADD COLUMN roster_confirmed_by integer;
UPDATE volley.team_entries SET roster_confirmed_at=COALESCE(roster_locked_at,registered_at,CURRENT_TIMESTAMP),roster_source_hash=NULL;
ALTER TABLE volley.players ADD COLUMN master_revision integer NOT NULL DEFAULT 0;
ALTER TABLE volley.team_staff ADD COLUMN master_revision integer NOT NULL DEFAULT 0;
ALTER TABLE volley.team_staff ADD COLUMN is_active smallint NOT NULL DEFAULT 1 CHECK(is_active IN (0,1));
ALTER TABLE volley.team_entry_staff ADD COLUMN staff_snapshot jsonb;
UPDATE volley.team_entry_staff es SET staff_snapshot=jsonb_build_object('first_name',s.first_name,'last_name',s.last_name,'role',s.role)
    FROM volley.team_staff s WHERE s.id=es.staff_id;
CREATE TABLE volley.team_data_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id integer NOT NULL REFERENCES volley.teams(id),actor_id integer REFERENCES volley.users(id),
    action text NOT NULL,person_kind text,person_id integer,entry_id integer,
    before_data jsonb,after_data jsonb,reason text,created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX team_data_history_team_idx ON volley.team_data_history(team_id,id DESC);
CREATE TABLE volley.team_roster_change_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id integer NOT NULL REFERENCES volley.teams(id),entry_id integer NOT NULL REFERENCES volley.team_entries(id) ON DELETE CASCADE,
    requested_by integer NOT NULL REFERENCES volley.users(id),reason text NOT NULL,proposal jsonb NOT NULL,before_data jsonb,base_revision integer NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
    decided_by integer REFERENCES volley.users(id),decision_reason text,created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,decided_at timestamptz
);
CREATE UNIQUE INDEX team_roster_one_pending ON volley.team_roster_change_requests(entry_id) WHERE status='pending';
