CREATE TABLE competition_workflows (
    competition_id integer PRIMARY KEY REFERENCES competitions(id) ON DELETE RESTRICT,
    revision integer NOT NULL DEFAULT 1,
    state text NOT NULL,
    updated_by integer REFERENCES users(id),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE competition_workflow_matches (
    match_id integer PRIMARY KEY REFERENCES matches(id) ON DELETE RESTRICT,
    competition_id integer NOT NULL REFERENCES competition_workflows(competition_id) ON DELETE RESTRICT,
    phase varchar(20) NOT NULL CHECK (phase IN ('group','knockout')),
    pool_name varchar(50),
    slot_key varchar(30),
    home_source text,
    away_source text,
    UNIQUE (competition_id,slot_key)
);
CREATE INDEX competition_workflow_matches_competition ON competition_workflow_matches(competition_id);
ALTER TABLE matches ADD COLUMN result_type varchar(20) NOT NULL DEFAULT 'normal';
ALTER TABLE matches ADD COLUMN forfeit_reason text;
CREATE TABLE competition_workflow_rulings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    competition_id integer NOT NULL REFERENCES competition_workflows(competition_id),
    match_id integer NOT NULL REFERENCES matches(id),
    original_snapshot text NOT NULL,
    awarded_result text NOT NULL,
    reason text NOT NULL,
    decided_by integer NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    reversed_at timestamptz,
    reversed_by integer REFERENCES users(id),
    reversal_reason text
);
CREATE INDEX competition_workflow_rulings_match ON competition_workflow_rulings(match_id);
