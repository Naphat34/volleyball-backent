const router = require('express').Router();
const auth = require('../middleware/authMiddleware');
const controller = require('../controllers/customVisController');
router.get('/public/:token', controller.publicView);
router.use(auth.verifyApprovedToken);
const readAccess = auth.hasAnyRole(['admin', 'score', 'scorer', 'statistician']);
router.get('/offline-permit', auth.canScoreMatches, controller.offlinePermit);
router.get('/', readAccess, controller.list);
router.post('/', auth.canScoreMatches, controller.create);
router.get('/athlete-options', readAccess, controller.athleteOptions);
router.put('/:id/athletes', readAccess, controller.linkAthlete);
router.get('/:id', readAccess, controller.read);
router.post('/:id/offline-checkout', auth.canScoreMatches, controller.offlineCheckout);
router.post('/:id/offline-cancel-checkout', auth.canScoreMatches, controller.offlineCancelCheckout);
router.post('/:id/offline-sync', auth.canScoreMatches, controller.offlineSync);
router.put('/:id', auth.canScoreMatches, controller.update);
router.post('/:id/command', auth.canScoreMatches, controller.command);
router.put('/:id/publish', auth.canScoreMatches, controller.publish);
router.post('/:id/reopen', auth.canScoreMatches, controller.reopen);
module.exports = router;
