const router = require('express').Router();
const auth = require('../middleware/authMiddleware');
const controller = require('../controllers/customVisController');
router.get('/public/:token', controller.publicView);
router.use(auth.verifyApprovedToken);
const readAccess = auth.canReadRecording;
router.get('/offline-permit', auth.canRecordVims, controller.offlinePermit);
router.get('/', readAccess, controller.list);
router.post('/', auth.canRecordVims, controller.create);
router.get('/athlete-options', readAccess, controller.athleteOptions);
router.put('/:id/athletes', readAccess, controller.linkAthlete);
router.get('/:id', readAccess, controller.read);
router.post('/:id/offline-checkout', auth.canRecordVims, controller.offlineCheckout);
router.post('/:id/offline-cancel-checkout', auth.canRecordVims, controller.offlineCancelCheckout);
router.post('/:id/offline-sync', auth.canRecordVims, controller.offlineSync);
router.put('/:id', auth.canRecordVims, controller.update);
router.post('/:id/command', auth.canRecordVims, controller.command);
const reviewWorkflow = (_req,res) => res.status(409).json({error:'Use /api/access review actions with a revision and reason'});
router.put('/:id/publish', auth.hasPermission('vims.publish'), reviewWorkflow);
router.post('/:id/reopen', auth.hasPermission('vims.reopen'), reviewWorkflow);
module.exports = router;
