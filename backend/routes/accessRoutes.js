const router=require('express').Router();
const auth=require('../middleware/authMiddleware');
const c=require('../controllers/accessController');
const corrections=require('../controllers/reviewCorrectionController');
router.use(auth.verifyApprovedToken);
router.get('/session',c.session);
router.get('/catalog',c.catalog);
router.get('/competitions',c.competitions);
router.get('/matches',c.matches);
router.get('/matches/match/:id/detail',require('../controllers/adminMatchDetailController').detail);
router.get('/users',c.users);
router.post('/users',c.createUser);
router.put('/users/:id',c.updateUser);
router.put('/users/:id/competitions',c.setCompetitions);
router.get('/reviews',c.reviews);
router.get('/matches/:kind/:id/preview',c.preview);
router.put('/matches/:kind/:id/competition',c.linkCompetition);
router.get('/matches/:kind/:id/:domain/correction',corrections.load);
router.put('/matches/:kind/:id/:domain/correction',corrections.save);
router.post('/matches/:kind/:id/:domain/:action',c.review);
module.exports=router;
